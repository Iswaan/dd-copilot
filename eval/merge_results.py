# -*- coding: utf-8 -*-
import json
import os

def main():
    if not os.path.exists('eval/q14_20_results.json'):
        print("[!] eval/q14_20_results.json not found! Ensure rerun_q14_20.py finished successfully.")
        return

    print("Loading original results...")
    with open('eval/results.json', 'r', encoding='utf-8') as f:
        original = json.load(f)

    print("Loading Q14-20 rerun results...")
    with open('eval/q14_20_results.json', 'r', encoding='utf-8') as f:
        new_subset = json.load(f)

    if len(new_subset) != 7:
        print(f"[!] Expected 7 items in rerun subset, got {len(new_subset)}.")
        return

    print("Merging new results into original list (indices 13-19)...")
    for i, new_item in enumerate(new_subset):
        original[13 + i] = new_item

    with open('eval/results.json', 'w', encoding='utf-8') as f:
        json.dump(original, f, indent=4)
        
    print("Saved merged results to eval/results.json.")

    # Regenerate markdown
    print("Recalculating true aggregates across all 20 questions...")
    metrics = ["faithfulness", "answer_relevancy", "context_precision", "context_recall"]
    aggregates = {m: 0.0 for m in metrics}
    counts = {m: 0 for m in metrics}

    for item in original:
        for m in metrics:
            if m in item and item[m] is not None:
                aggregates[m] += item[m]
                counts[m] += 1

    out_md = "eval/results.md"
    with open(out_md, "w", encoding="utf-8") as f:
        f.write("# RAGAS Evaluation Results\\n\\n")
        f.write("> **Note on Judge Model**: The RAGAS LLM judge used here is local llama3:latest (via Ollama), while the actual answers were generated by llama-3.3-70b-versatile via Groq. This ensures we don't hit strict rate limits during the extensive scoring phase.\\n\\n")
        f.write("## Aggregate Metrics\\n")
        for m in metrics:
            if counts[m] > 0:
                avg = aggregates[m] / counts[m]
                f.write(f"- **{m}**: {avg:.4f}\\n")
        
        f.write("\\n> **Note**: answer_relevancy occasionally scores 0.0 on appropriately-hedged/partial answers. This is a known limitation of the metric, which penalizes answers that don't directly restate question terms - even when hedging is the correct behavior. faithfulness and context_recall are more reliable signals for this pipeline's honesty-preserving design than answer_relevancy alone.\\n\\n")
        
        f.write("## Per-Question Results\\n\\n")
        for row in original:
            f.write(f"### Q: {row.get('user_input', row.get('question', ''))}\\n")
            f.write(f"**Ground Truth**: {row.get('reference', row.get('ground_truth', ''))}\\n\\n")
            f.write(f"**Generated Answer**: {row.get('response', row.get('answer', ''))}\\n\\n")
            f.write("**Scores**:\\n")
            for m in metrics:
                if m in row and row[m] is not None:
                    f.write(f"- {m}: {row[m]:.4f}\\n")
            f.write("\\n---\\n")

    print("Regenerated eval/results.md with true aggregates.")

if __name__ == '__main__':
    main()
